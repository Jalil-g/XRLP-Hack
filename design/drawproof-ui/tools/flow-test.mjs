import { launch, sleep } from './cdp.mjs'
const out = process.argv[2]
const BASE = 'http://localhost:3100'
const page = await launch()
const log = (...a) => console.log(...a)
try {
  await page.goto(`${BASE}/inspector`)
  log('queue has Start audit:', await page.has('Start audit'))
  await page.clickText('Start audit'); await sleep(1500)
  log('on audit page:', await page.evaluate('location.pathname'))
  await page.clickText('Builder resubmits evidence'); await sleep(400)
  log('changed banner:', await page.has('Evidence changed to v3'))
  await page.screenshot(`${out}/t1-changed.png`)
  await page.clickText('Reload evidence'); await sleep(500)
  log('now v3:', await page.has('Evidence v3'))
  await page.clickText('Continue'); await sleep(400)
  log('checklist step:', await page.has('Mark all done'))
  await page.clickText('Mark all done'); await sleep(300)
  await page.clickText('Partial', '[role=radio]'); await sleep(300)  // first row set to Partial -> needs note
  log('continue enabled w/o note (should be false):', await page.evaluate(`!![...document.querySelectorAll('button')].find(b=>b.innerText.trim()==='Continue' && !b.disabled)`))
  await page.evaluate(`(() => { const i=document.querySelector('input[placeholder="What is missing?"]'); const s=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set; s.call(i,'North wall open'); i.dispatchEvent(new Event('input',{bubbles:true})) })()`)
  await sleep(300)
  await page.screenshot(`${out}/t2-checklist.png`)
  await page.clickText('Continue'); await sleep(400)
  log('photos step:', await page.has('Add photo'))
  await page.clickText('Add photo'); await sleep(300); await page.clickText('Add photo'); await sleep(500)
  await page.screenshot(`${out}/t3-photos.png`)
  await page.clickText('Continue'); await sleep(500)
  log('review step:', await page.has('filing a signed audit'))
  await page.screenshot(`${out}/t4-review.png`)
  await page.clickText('Load key to sign'); await sleep(600)
  await page.clickText('Use demo inspector key'); await sleep(1500)
  await page.screenshot(`${out}/t5-key.png`)
  const closed = await page.evaluate(`!!document.querySelector('[role=dialog]')`)
  log('key dialog open after load:', closed)
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 }); await sleep(500)
  await page.clickText('Sign and file audit'); await sleep(700)
  await page.screenshot(`${out}/t6-signing-review.png`)
  await page.clickText('Sign and file audit', '[role=dialog] button'); await sleep(2600)
  await page.screenshot(`${out}/t7-confirmed.png`)
  log('confirmed text:', await page.has('Confirmed'))
} catch (e) { log('FAIL', e.message); await page.screenshot(`${out}/fail.png`).catch(()=>{}) }
page.close()
